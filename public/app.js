function renderMovieRow(row, index) {
  const rowId = `movie-row-${index}`;
  return `
    <section class="movie-row" aria-label="${escapeHTML(row.title)}">
      <div class="movie-row-heading">
        <h3>${escapeHTML(row.title)}</h3>
        <div class="row-controls">
          <button type="button" data-scroll="-1" data-target="${rowId}" aria-label="Scroll movies left">‹</button>
          <button type="button" data-scroll="1" data-target="${rowId}" aria-label="Scroll movies right">›</button>
        </div>
      </div>
      <div class="movie-row-track" id="${rowId}">${row.movies.map(renderMovieCard).join("")}</div>
    </section>
  `;
}

function showToast(message) {
  const toast = document.createElement("div");
  toast.className = "toast";
  toast.textContent = message;
  elements.toastRegion.append(toast);
  window.setTimeout(() => toast.remove(), 3200);
}

async function request(url, options = {}) {
  const response = await fetch(apiUrl(url), {
    ...options,
    credentials: "include",
    headers: {
      ...(options.body instanceof FormData ? {} : { "Content-Type": "application/json" }),
      ...(options.headers || {}),
    },
  });
  let result;
  try {
    result = await response.json();
  } catch {
    result = {};
  }
  if (!response.ok) throw new Error(result.error || `Request failed (${response.status}).`);
  return result;
}

