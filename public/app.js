function bindUploadPreviews(form) {
  const videoInput = form.querySelector("#video-file");
  const posterInput = form.querySelector("#poster-file");

  videoInput.addEventListener("change", () => {
    const file = videoInput.files[0];
    form.querySelector("#video-file-name").textContent = file
      ? `${file.name} · ${(file.size / (1024 * 1024)).toFixed(1)} MB`
      : t("videoDrop");
    form.querySelector("#video-drop").classList.toggle("file-selected", Boolean(file));
  });

  posterInput.addEventListener("change", () => {
    const file = posterInput.files[0];
    const drop = form.querySelector("#poster-drop");
    drop.querySelector(".upload-preview")?.remove();
    drop.classList.toggle("file-selected", Boolean(file));
    if (!file) return;
    const image = document.createElement("img");
    image.className = "upload-preview";
    image.alt = "";
    image.src = URL.createObjectURL(file);
    drop.prepend(image);
    form.querySelector("#poster-file-name").textContent = file.name;
  });

  for (const drop of form.querySelectorAll(".upload-drop")) {
    drop.addEventListener("dragover", (event) => {
      event.preventDefault();
      drop.classList.add("drag-over");
    });
    drop.addEventListener("dragleave", (event) => {
      if (!drop.contains(event.relatedTarget)) drop.classList.remove("drag-over");
    });
    drop.addEventListener("drop", (event) => {
      event.preventDefault();
      drop.classList.remove("drag-over");
      const input = drop.querySelector('input[type="file"]');
      if (!input || !event.dataTransfer.files.length) return;
      input.files = event.dataTransfer.files;
      input.dispatchEvent(new Event("change", { bubbles: true }));
    });
  }
}

