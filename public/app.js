const t = (key) => translations[state.language][key] || translations.en[key] || key;
const API_BASE = String(globalThis.TAZAMA_API_BASE || "").replace(/\/+$/, "");
const apiUrl = (url) => `${API_BASE}${url}`;
const mediaUrl = (url) => url ? apiUrl(url) : "";
